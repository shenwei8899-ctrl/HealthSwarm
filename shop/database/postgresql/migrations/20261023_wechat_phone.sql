-- PostgreSQL only. Apply explicitly to the isolated database first; never auto-run on API requests.
BEGIN;
CREATE TABLE IF NOT EXISTS fa_shop_phone_binding (
    user_id INTEGER PRIMARY KEY REFERENCES fa_user(id),
    country_code VARCHAR(4) NOT NULL,
    national_number VARCHAR(15) NOT NULL,
    app_id VARCHAR(18) NOT NULL,
    verification_source VARCHAR(32) NOT NULL DEFAULT 'wechat_phone',
    verified_at BIGINT NOT NULL,
    CONSTRAINT shop_phone_binding_number_unique UNIQUE (country_code, national_number)
);
CREATE TABLE IF NOT EXISTS fa_shop_phone_binding_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES fa_user(id),
    key_hash CHAR(64) NOT NULL,
    code_hash CHAR(64) NOT NULL UNIQUE,
    app_id VARCHAR(18) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('processing','succeeded','failed','uncertain')),
    result_json TEXT NOT NULL DEFAULT '{}',
    error_code INTEGER NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    CONSTRAINT shop_phone_binding_request_key UNIQUE (user_id, key_hash)
);
CREATE INDEX IF NOT EXISTS shop_phone_binding_request_user_time ON fa_shop_phone_binding_request(user_id,created_at);
COMMIT;
