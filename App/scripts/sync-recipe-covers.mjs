// Backend owns the reviewed media catalog. The mini-program consumes this generated projection for older APIs.
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import assert from 'node:assert/strict'
const app=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')
const catalog=JSON.parse(fs.readFileSync(path.join(app,'../agent/Yuxi-main/backend/package/yuxi/services/data/recipe_covers.json'),'utf8'))
const target=path.join(app,'src/data/recipe-covers.js')
const content='// Generated by scripts/sync-recipe-covers.mjs from the backend reviewed catalog.\nexport const recipeCovers = '+JSON.stringify(catalog.covers,null,2)+'\n'
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),content,'Regenerate the recipe cover projection')
else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,content)}
